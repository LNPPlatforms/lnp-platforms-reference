-- money and assignment on a job: only dispatch or job approvers change them (a worker can fix notes and scope)
create or replace function private.guard_job() returns trigger
language plpgsql security definer set search_path = public, private as $$
begin
  if auth.uid() is null or private.can('jobs', 3) or private.can('dispatch', 2) then return new; end if;
  if new.price is distinct from old.price or new.pay_amount is distinct from old.pay_amount
     or (new.assigned_to is distinct from old.assigned_to and not (old.assigned_to is null and new.assigned_to = auth.uid()))
     or new.company_id is distinct from old.company_id or new.scheduled_start is distinct from old.scheduled_start or new.scheduled_end is distinct from old.scheduled_end
     or new.archived_at is distinct from old.archived_at then
    raise exception 'Only dispatch or a manager can change the price, pay, worker, place or time on a job';
  end if;
  return new;
end $$;
create trigger guard_job before update on public.jobs for each row execute function private.guard_job();
create or replace function private.touch() returns trigger language plpgsql as $$ begin new.updated_at := now(); return new; end $$;
create trigger touch_jobs before update on public.jobs for each row execute function private.touch();
create trigger touch_job_schedules before update on public.job_schedules for each row execute function private.touch();

-- the account's check-in distance and auto-approve rules
create or replace function private.acct_setting(k text) returns jsonb
language sql stable security definer set search_path = public, private as $$
  select settings->k from account_settings where tenant_id = private.current_tenant()
$$;

-- the closest pin on a location and how far away the point is (null when the location has no pins)
create or replace function private.nearest_pin(p_company uuid, p_lat double precision, p_lng double precision, out pin_id uuid, out feet double precision, out radius int)
language sql stable security definer set search_path = public, private as $$
  select p.id, private.feet_between(p.lat, p.lng, p_lat, p_lng),
         coalesce(p.radius_ft, (private.acct_setting('gps_radius_ft')#>>'{}')::int, 500)
  from location_pins p where p.company_id = p_company and p.archived_at is null
  order by private.feet_between(p.lat, p.lng, p_lat, p_lng) limit 1
$$;

-- would this finished job pass the account's auto-approve rules
create or replace function private.job_auto_ok(j jobs) returns boolean
language plpgsql stable security definer set search_path = public, private as $$
declare r jsonb := coalesce(private.acct_setting('auto_approve')->'jobs', '{}'::jsonb); costs numeric;
begin
  if not coalesce((r->>'on')::boolean, false) then return false; end if;
  if coalesce((r->>'in_radius')::boolean, true) and (j.flags && array['far_arrive', 'far_leave', 'no_gps']) then return false; end if;
  if coalesce((r->>'no_flags')::boolean, true) and (j.flags && array['problem', 'late', 'over_cost']) then return false; end if;
  if coalesce((r->>'on_time')::boolean, true) and j.scheduled_end is not null
     and coalesce(j.left_at, j.completed_at) > j.scheduled_end + make_interval(mins => coalesce((r->>'grace_min')::int, 30)) then return false; end if;
  select coalesce(sum(amount), 0) into costs from job_costs where job_id = j.id and archived_at is null;
  if (r->>'max_costs') is not null and costs > (r->>'max_costs')::numeric then return false; end if;
  if exists (select 1 from job_costs where job_id = j.id and archived_at is null and category is null) then return false; end if;
  return true;
end $$;

-- the worker's phone: move a job along. Arrived and Left check GPS against the location's pins.
create or replace function public.job_step(p_job uuid, p_status text, p_lat double precision default null, p_lng double precision default null,
                                           p_accuracy double precision default null, p_note text default null)
returns jsonb language plpgsql security definer set search_path = public, private as $$
declare j jobs; np_pin uuid; np_feet double precision; np_radius int; far boolean := false; flag text; rv uuid; order_ text[] := array['scheduled', 'accepted', 'en_route', 'arrived', 'started', 'completed', 'left'];
begin
  select * into j from jobs where id = p_job and tenant_id = private.current_tenant() and archived_at is null for update;
  if j.id is null or not private.feature_on('jobs') then raise exception 'Job not found'; end if;
  if not (j.assigned_to = auth.uid() or (private.can('dispatch', 2) and private.in_scope('dispatch', coalesce(j.assigned_to, j.created_by), j.divisions))) then
    raise exception 'This job isn''t assigned to you';
  end if;
  if p_status not in ('accepted', 'en_route', 'arrived', 'started', 'completed', 'left', 'cancelled', 'no_show') then raise exception 'Unknown step %', p_status; end if;
  if j.status in ('cancelled', 'no_show', 'left') then raise exception 'This job is already closed'; end if;
  if p_status = 'cancelled' and not private.can('dispatch', 2) then raise exception 'Only dispatch can cancel a job'; end if;
  if array_position(order_, p_status) is not null and array_position(order_, p_status) <= array_position(order_, j.status) then
    raise exception 'That step is already done';
  end if;

  if p_status in ('arrived', 'left') then
    if p_lat is null or p_lng is null then
      flag := 'no_gps';
    else
      select n.pin_id, n.feet, n.radius into np_pin, np_feet, np_radius from private.nearest_pin(j.company_id, p_lat, p_lng) n;
      if np_pin is not null and np_feet > np_radius then far := true; flag := case when p_status = 'arrived' then 'far_arrive' else 'far_leave' end; end if;
      -- no pin yet: the first arrival becomes the suggested pin for a manager to confirm
      if np_pin is null and p_status = 'arrived' then
        insert into work_reviews (kind, job_id, company_id, divisions, worker_id, summary, details)
        values ('pin_change', j.id, j.company_id, j.divisions, auth.uid(), 'First check-in here: set the pin?',
                jsonb_build_object('lat', p_lat, 'lng', p_lng, 'accuracy_m', p_accuracy, 'first', true));
      end if;
    end if;
  end if;

  insert into job_events (job_id, kind, status, lat, lng, accuracy_m, distance_ft, pin_id, flagged, note)
  values (j.id, 'status', p_status, p_lat, p_lng, p_accuracy, np_feet, np_pin, far or coalesce(flag = 'no_gps', false), nullif(trim(coalesce(p_note, '')), ''));

  update jobs set status = p_status,
    flags = case when flag is not null and not (flag = any(flags)) then flags || flag else flags end,
    accepted_at = case when p_status = 'accepted' then now() else accepted_at end,
    en_route_at = case when p_status = 'en_route' then now() else en_route_at end,
    arrived_at = case when p_status = 'arrived' then now() else arrived_at end,
    started_at = case when p_status = 'started' then now() else started_at end,
    completed_at = case when p_status = 'completed' then now() else completed_at end,
    left_at = case when p_status = 'left' then now() else left_at end,
    assigned_to = coalesce(assigned_to, case when p_status = 'accepted' then auth.uid() end)
  where id = j.id returning * into j;

  if far then
    insert into work_reviews (kind, ref_id, job_id, company_id, divisions, worker_id, summary, details)
    values ('gps_flag', j.id, j.id, j.company_id, j.divisions, auth.uid(),
            format('%s %s ft from the pin (allowed %s)', case when p_status = 'arrived' then 'Arrived' else 'Left' end, round(np_feet), np_radius),
            jsonb_build_object('lat', p_lat, 'lng', p_lng, 'feet', round(np_feet), 'radius', np_radius, 'pin_id', np_pin, 'step', p_status));
  end if;

  -- finished: Completed opens the review; Left (or Completed when there is no Left step) can auto-approve it
  if p_status = 'completed' and not exists (select 1 from work_reviews where kind = 'job_done' and ref_id = j.id and status in ('pending', 'auto', 'approved')) then
    insert into work_reviews (kind, ref_id, job_id, company_id, divisions, worker_id, summary)
    values ('job_done', j.id, j.id, j.company_id, j.divisions, coalesce(j.assigned_to, auth.uid()), j.title) returning id into rv;
    update jobs set approval = 'pending' where id = j.id;
  end if;
  if p_status = 'left' or (p_status = 'completed' and not private.feature_on('dispatch')) then
    select * into j from jobs where id = j.id;
    if private.job_auto_ok(j) then
      update work_reviews set status = 'auto', decided_at = now(), decision_note = 'Passed the auto-approve rules'
       where kind = 'job_done' and ref_id = j.id and status = 'pending';
      update jobs set approval = 'auto' where id = j.id and approval = 'pending';
    end if;
  end if;
  return jsonb_build_object('status', p_status, 'flag', flag, 'feet', round(np_feet), 'radius', np_radius);
end $$;

-- photo, note or problem on a job (photo_path is in the job-photos bucket)
create or replace function public.job_note(p_job uuid, p_kind text, p_note text, p_photo text default null)
returns uuid language plpgsql security definer set search_path = public, private as $$
declare j jobs; out uuid;
begin
  select * into j from jobs where id = p_job and tenant_id = private.current_tenant();
  if j.id is null then raise exception 'Job not found'; end if;
  if not (j.assigned_to = auth.uid() or (private.can('jobs', 2) and private.in_scope('jobs', coalesce(j.assigned_to, j.created_by), j.divisions))) then raise exception 'This job isn''t yours'; end if;
  if p_kind not in ('photo', 'note', 'problem') then raise exception 'Unknown entry'; end if;
  if p_photo is not null and split_part(p_photo, '/', 1) <> private.current_tenant()::text then raise exception 'Photo is in the wrong place'; end if;
  insert into job_events (job_id, kind, note, photo_path) values (j.id, p_kind, nullif(trim(coalesce(p_note, '')), ''), p_photo) returning id into out;
  if p_kind = 'problem' then update jobs set flags = case when 'problem' = any(flags) then flags else flags || 'problem'::text end where id = j.id; end if;
  return out;
end $$;

-- the worker says the pin is in the wrong spot: their GPS and a photo go to a manager
create or replace function public.pin_report(p_job uuid, p_lat double precision, p_lng double precision, p_accuracy double precision, p_note text, p_photo text)
returns uuid language plpgsql security definer set search_path = public, private as $$
declare j jobs; out uuid; np_pin uuid; np_feet double precision;
begin
  select * into j from jobs where id = p_job and tenant_id = private.current_tenant();
  if j.id is null or not (j.assigned_to = auth.uid() or private.can('dispatch', 2)) then raise exception 'Job not found'; end if;
  select n.pin_id, n.feet into np_pin, np_feet from private.nearest_pin(j.company_id, p_lat, p_lng) n;
  insert into work_reviews (kind, job_id, company_id, divisions, worker_id, summary, details)
  values ('pin_change', j.id, j.company_id, j.divisions, auth.uid(), coalesce(nullif(trim(p_note), ''), 'The check-in spot is wrong'),
          jsonb_build_object('lat', p_lat, 'lng', p_lng, 'accuracy_m', p_accuracy, 'photo', p_photo, 'pin_id', np_pin, 'feet', round(np_feet)))
  returning id into out;
  return out;
end $$;

-- other costs on a job. A preset fills the item, price and (hidden) category; a one-off goes to Review to categorize.
create or replace function public.job_cost_add(p_job uuid, p_preset uuid, p_item text, p_qty numeric, p_unit_cost numeric, p_notes text)
returns uuid language plpgsql security definer set search_path = public, private as $$
declare j jobs; pr cost_presets; out uuid;
begin
  if not private.feature_on('costs') then raise exception 'Other costs are switched off for this account'; end if;
  select * into j from jobs where id = p_job and tenant_id = private.current_tenant();
  if j.id is null or not (j.assigned_to = auth.uid() or (private.can('costs', 2) and private.in_scope('jobs', coalesce(j.assigned_to, j.created_by), j.divisions))) then raise exception 'Job not found'; end if;
  if j.approval in ('approved', 'auto') and not private.can('costs', 3) then raise exception 'This job is already approved. Ask a manager to add the cost.'; end if;
  if p_preset is not null then select * into pr from cost_presets where id = p_preset and tenant_id = private.current_tenant() and archived_at is null; end if;
  insert into job_costs (job_id, preset_id, item, qty, unit_cost, notes, category)
  values (j.id, pr.id, coalesce(nullif(trim(p_item), ''), pr.item), coalesce(p_qty, 1), coalesce(p_unit_cost, pr.default_cost, 0), nullif(trim(coalesce(p_notes, '')), ''), pr.category)
  returning id into out;
  if pr.id is null then
    insert into work_reviews (kind, ref_id, job_id, company_id, divisions, worker_id, summary, details)
    values ('cost_category', out, j.id, j.company_id, j.divisions, auth.uid(), trim(p_item),
            jsonb_build_object('qty', coalesce(p_qty, 1), 'unit_cost', coalesce(p_unit_cost, 0), 'notes', p_notes));
  end if;
  return out;
end $$;

create or replace function public.job_cost_remove(p_cost uuid) returns void
language plpgsql security definer set search_path = public, private as $$
declare c job_costs; j jobs;
begin
  select * into c from job_costs where id = p_cost and tenant_id = private.current_tenant();
  select * into j from jobs where id = c.job_id;
  if c.id is null or not (c.created_by = auth.uid() and j.approval not in ('approved', 'auto') or private.can('costs', 3)) then raise exception 'You can''t remove that cost'; end if;
  update job_costs set archived_at = now() where id = c.id;
  update work_reviews set status = 'dismissed', decided_at = now(), decided_by = auth.uid(), decision_note = 'Cost removed' where kind = 'cost_category' and ref_id = c.id and status = 'pending';
end $$;

-- someone without preset rights suggests one; someone with them approves it in Review
create or replace function public.preset_suggest(p_item text, p_cost numeric, p_category text, p_note text)
returns uuid language plpgsql security definer set search_path = public, private as $$
declare out uuid;
begin
  if not private.is_internal() then raise exception 'Not allowed'; end if;
  insert into work_reviews (kind, worker_id, summary, details) values ('preset_suggestion', auth.uid(), trim(p_item),
    jsonb_build_object('item', trim(p_item), 'default_cost', p_cost, 'category', p_category, 'note', p_note)) returning id into out;
  return out;
end $$;

-- a manager decides a field-work item. decision: approve, return (send back with a note) or dismiss.
-- extra: {category, save_preset} for cost_category; {label, radius_ft, new_pin} for pin_change.
create or replace function public.work_review_decide(p_id uuid, p_decision text, p_note text default null, p_extra jsonb default '{}'::jsonb)
returns void language plpgsql security definer set search_path = public, private as $$
declare w work_reviews; c job_costs;
begin
  select * into w from work_reviews where id = p_id and tenant_id = private.current_tenant() for update;
  if w.id is null then raise exception 'Not found'; end if;
  if not (private.can('review', 3) and private.in_scope('review', w.worker_id, w.divisions)) then raise exception 'You can''t decide this one'; end if;
  if w.worker_id = auth.uid() and not private.is_admin() and w.kind in ('job_done', 'timesheet') then raise exception 'Someone else has to approve your own work'; end if;
  if w.status not in ('pending', 'auto') then raise exception 'Already decided'; end if;
  if p_decision not in ('approve', 'return', 'dismiss') then raise exception 'Unknown decision'; end if;
  if p_decision = 'return' and length(trim(coalesce(p_note, ''))) = 0 then raise exception 'Say why it''s going back'; end if;

  if w.kind = 'job_done' then
    update jobs set approval = case p_decision when 'approve' then 'approved' when 'return' then 'returned' else approval end,
                    status = case when p_decision = 'return' then 'started' else status end
     where id = w.ref_id;
  elsif w.kind = 'timesheet' then
    update time_entries set status = case p_decision when 'approve' then 'approved' when 'return' then 'returned' else status end where id = w.ref_id;
  elsif w.kind = 'pin_change' and p_decision = 'approve' then
    if not private.can('dispatch', 3) then raise exception 'Moving a pin needs dispatch approval rights'; end if;
    if (w.details->>'pin_id') is not null and not coalesce((p_extra->>'new_pin')::boolean, false) then
      update location_pins set lat = (w.details->>'lat')::double precision, lng = (w.details->>'lng')::double precision,
             radius_ft = coalesce((p_extra->>'radius_ft')::int, radius_ft) where id = (w.details->>'pin_id')::uuid and tenant_id = w.tenant_id;
    else
      insert into location_pins (company_id, label, lat, lng, radius_ft, is_primary)
      values (w.company_id, coalesce(nullif(trim(p_extra->>'label'), ''), case when coalesce((w.details->>'first')::boolean, false) then 'Main' else 'Check-in spot' end),
              (w.details->>'lat')::double precision, (w.details->>'lng')::double precision, (p_extra->>'radius_ft')::int,
              not exists (select 1 from location_pins where company_id = w.company_id and archived_at is null));
    end if;
  elsif w.kind = 'cost_category' and p_decision = 'approve' then
    if coalesce(p_extra->>'category', '') not in ('materials', 'parts', 'disposal', 'equipment', 'fuel', 'supplies', 'subcontract', 'other') then raise exception 'Pick a category'; end if;
    update job_costs set category = p_extra->>'category' where id = w.ref_id returning * into c;
    if coalesce((p_extra->>'save_preset')::boolean, false) then
      if not private.can('costs', 4) then raise exception 'Saving presets needs cost management rights. Escalate it with Suggest as preset.'; end if;
      insert into cost_presets (item, default_cost, category) values (c.item, c.unit_cost, c.category);
    end if;
  elsif w.kind = 'preset_suggestion' and p_decision = 'approve' then
    if not private.can('costs', 4) then raise exception 'Saving presets needs cost management rights'; end if;
    insert into cost_presets (item, default_cost, category) values (w.details->>'item', nullif(w.details->>'default_cost', '')::numeric,
      case when w.details->>'category' in ('materials', 'parts', 'disposal', 'equipment', 'fuel', 'supplies', 'subcontract', 'other') then w.details->>'category' else 'other' end);
  end if;

  update work_reviews set status = case p_decision when 'approve' then 'approved' when 'return' then 'returned' else 'dismissed' end,
         decided_by = auth.uid(), decided_at = now(), decision_note = nullif(trim(coalesce(p_note, '')), '')
   where id = w.id;
end $$;

-- repeat schedules: create the upcoming jobs through p_days from today (skips slots that already have a job)
create or replace function public.schedules_generate(p_days int default 21)
returns int language plpgsql security definer set search_path = public, private as $$
declare s job_schedules; d date; upto date := current_date + least(greatest(p_days, 1), 90); n int := 0; dow int; startt time; dur int; every int; ok boolean; st timestamptz;
begin
  if not private.feature_on('jobs') or not private.can('jobs', 1) then return 0; end if;
  for s in select * from job_schedules where tenant_id = private.current_tenant() and active and (ends_on is null or ends_on >= current_date) loop
    startt := coalesce((s.rule->>'start_time')::time, '09:00'); dur := coalesce((s.rule->>'duration_min')::int, 60); every := greatest(coalesce((s.rule->>'every')::int, 1), 1);
    d := greatest(s.starts_on, current_date, coalesce(s.generated_through + 1, s.starts_on));
    while d <= least(upto, coalesce(s.ends_on, upto)) loop
      dow := extract(isodow from d);
      ok := case s.rule->>'freq'
        when 'daily' then (d - s.starts_on) % every = 0
        when 'weekly' then (s.rule->'days') @> to_jsonb(dow) and ((d - s.starts_on) / 7) % every = 0
        when 'monthly' then extract(day from d) = coalesce((s.rule->>'day_of_month')::int, extract(day from s.starts_on))
                            and ((extract(year from d) - extract(year from s.starts_on)) * 12 + extract(month from d) - extract(month from s.starts_on))::int % every = 0
        else false end;
      if ok then
        st := (d + startt) at time zone s.timezone;
        insert into jobs (tenant_id, company_id, divisions, schedule_id, source, title, service_type, scope, scheduled_start, scheduled_end, price, assigned_to, custom, created_by)
        values (s.tenant_id, s.company_id, s.divisions, s.id, 'schedule', s.title, s.service_type, s.scope, st, st + make_interval(mins => dur), s.price, s.assigned_to, s.custom, s.created_by)
        on conflict (schedule_id, scheduled_start) where schedule_id is not null do nothing;
        if found then n := n + 1; end if;
      end if;
      d := d + 1;
    end loop;
    update job_schedules set generated_through = greatest(coalesce(generated_through, upto), upto) where id = s.id;
  end loop;
  return n;
end $$;

-- changing a schedule updates the upcoming jobs from it that nobody has started (and aren't edited one-offs)
create or replace function public.schedule_apply(p_schedule uuid) returns int
language plpgsql security definer set search_path = public, private as $$
declare n int;
begin
  if not private.can('jobs', 4) then raise exception 'Only someone who manages jobs can change a schedule'; end if;
  delete from jobs where schedule_id = p_schedule and tenant_id = private.current_tenant() and status = 'scheduled' and scheduled_start > now()
    and not exists (select 1 from job_events e where e.job_id = jobs.id) and not exists (select 1 from job_costs c where c.job_id = jobs.id)
    and coalesce((custom->>'_edited')::boolean, false) = false;
  get diagnostics n = row_count;
  update job_schedules set generated_through = current_date - 1 where id = p_schedule;
  perform public.schedules_generate(21);
  return n;
end $$;

-- a job from an accepted proposal: the organization, its divisions and the setup price carry over
create or replace function public.job_from_proposal(p_proposal uuid, p_title text default null, p_start timestamptz default null)
returns uuid language plpgsql security definer set search_path = public, private as $$
declare pr record; out uuid;
begin
  if not private.can('jobs', 2) then raise exception 'You can''t add jobs'; end if;
  select p.*, c.divisions as cdivs, c.name as cname,
         (select v.setup_total from proposal_versions v where v.proposal_id = p.id and v.version = coalesce(p.accepted_version, p.version)) as setup
    into pr from proposals p join companies c on c.id = p.company_id where p.id = p_proposal and p.tenant_id = private.current_tenant();
  if pr.id is null then raise exception 'Proposal not found'; end if;
  insert into jobs (company_id, divisions, proposal_id, source, title, scheduled_start, scheduled_end, price)
  values (pr.company_id, pr.cdivs, pr.id, 'proposal', coalesce(nullif(trim(p_title), ''), pr.cname), p_start, p_start + interval '1 hour', pr.setup)
  returning id into out;
  return out;
end $$;

