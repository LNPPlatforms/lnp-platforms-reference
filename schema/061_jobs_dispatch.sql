-- Shortcuts: saved filters on any list (Review, jobs, organizations...). Personal by default, shareable with the team.
create table if not exists public.shortcuts (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null default private.current_tenant() references public.tenants(id) on delete cascade,
  user_id uuid not null default auth.uid() references public.app_users(id),
  screen text not null check (screen ~ '^[a-z_]{1,30}$'),
  name text not null check (length(trim(name)) between 1 and 40),
  filters jsonb not null default '{}'::jsonb,
  shared boolean not null default false,
  sort int not null default 0,
  created_at timestamptz not null default now()
);
create index if not exists shortcuts_screen on public.shortcuts (tenant_id, screen);
alter table public.shortcuts enable row level security;
create policy "see shortcuts" on public.shortcuts for select using (tenant_id = private.current_tenant() and private.is_internal() and (user_id = auth.uid() or shared));
create policy "own shortcuts" on public.shortcuts for all using (tenant_id = private.current_tenant() and user_id = auth.uid())
  with check (tenant_id = private.current_tenant() and user_id = auth.uid());
revoke all on public.shortcuts from anon, authenticated;
grant select, insert, update, delete on public.shortcuts to authenticated;

