-- 061: jobs, repeat schedules, dispatch, GPS check-in, other costs and field work in Review (Oct 29, 2026).
-- Jobs: made from an accepted proposal, from Quick Add, from a website booking form or by a repeat schedule.
-- Repeat schedules: a rule (every weeknight at this property) that keeps upcoming jobs created a few weeks ahead.
--   Changing one job never touches the rest; changing the schedule only touches jobs that haven't started.
-- Worker flow on the phone: Accepted, En route, Arrived, Started, Completed, Left. Arrived and Left record GPS and
--   flag it when the worker is farther than the check-in distance from every pin on that location.
-- Wrong pin: the worker reports the spot with a photo; a manager approves and the pin moves (the address never does).
-- Other costs: item and amount, optional quantity and notes. Categories are set behind the scenes on presets;
--   a one-off item goes to Review for a manager to categorize. Other costs never go to accounting.
-- Review: field work lands in work_reviews (finished jobs, timesheets, GPS flags, pin changes, cost categories,
--   preset suggestions). Auto-approve rules can approve clean items on their own; those land already done.
-- Everything here only works when the account has the feature switched on.

